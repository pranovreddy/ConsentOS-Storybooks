// Generates src/index.ts from src/components so every component is exported by name.
import { readdirSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const root = new URL('../src/', import.meta.url).pathname
const walk = (d) => readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]))
const files = walk(join(root, 'components')).filter((f) => f.endsWith('.vue')).sort()

const lines = ['// Generated by scripts/gen-index.mjs. Do not edit.', "import './lib.css'", '']
for (const f of files) {
  const name = f.split('/').pop().replace('.vue', '')
  lines.push(`export { default as ${name} } from './${relative(root, f)}'`)
}
lines.push('', "export { useToast } from './components/feedback/ToastStack.vue'", "export { statusMap } from './components/display/StatusChip.vue'", "export { icons, iconNames, type IconName } from './icons'", '')
writeFileSync(join(root, 'index.ts'), lines.join('\n'))
console.log(`index.ts: ${files.length} components`)
